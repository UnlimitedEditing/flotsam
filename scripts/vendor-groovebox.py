"""Rebuilds public/viewers/groovebox/studio.html from the upstream Groove Box Score Studio.

    python scripts/vendor-groovebox.py <path to a checkout of github.com/UnlimitedEditing/groovebox>

The page is a patched COPY (see the comment the script writes at the top of the file): local scripts instead of a
CDN, an embedded mode, instrument sounds only after the user allows the download, and the bridge to the app
(src/results/frame/bridge.ts). The libraries in vendor/ are pinned: pako 1.0.11, upng-js 2.1.0, abcjs 6.4.4.
"""
import os
import sys

src_dir = sys.argv[1] if len(sys.argv) > 1 else "."
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "public", "viewers", "groovebox", "studio.html")
s = open(os.path.join(src_dir, "studio.html"), encoding="utf8").read()


def rep(a, b):
    global s
    assert a in s, "upstream changed, patch no longer applies: " + a[:70]
    s = s.replace(a, b, 1)


rep('<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/abcjs@6.4.4/abcjs-audio.css">', '<link rel="stylesheet" href="vendor/abcjs-audio.css">')
rep('<script src="https://cdn.jsdelivr.net/npm/pako@1.0.11/dist/pako.min.js"></script>', '<script src="vendor/pako.min.js"></script>')
rep('<script src="https://cdn.jsdelivr.net/npm/upng-js@2.1.0/UPNG.js"></script>', '<script src="vendor/UPNG.js"></script>')
rep('<script src="https://cdn.jsdelivr.net/npm/abcjs@6.4.4/dist/abcjs-basic-min.js"></script>', '<script src="vendor/abcjs-basic-min.js"></script>')
rep("<title>YuE2 Score Studio</title>", "<title>YuE2 Score Studio (Flotsam copy)</title>")

rep(
    "<!doctype html>\n",
    """<!doctype html>
<!-- Vendored copy of the Groove Box "Score Studio" (https://github.com/UnlimitedEditing/groovebox, MIT) for Flotsam.
     Generated by scripts/vendor-groovebox.py. Changes from the original: scripts and styles are local (vendor/)
     instead of from a CDN; embedded mode (the body.embed rules below) hides the file picker, footer and downloads;
     instrument sounds are NOT downloaded until the user allows it (abcjs would otherwise fetch them from
     paulrosen.github.io on play); a bridge script at the end talks to the app (src/results/frame/bridge.ts).
     Nothing here sends anything anywhere. -->
""",
)

rep(
    "</style>\n",
    """  /* embedded in Flotsam: no file picker, no footer, no page heading; the app's own bar closes the panel */
  body.embed header, body.embed #drop, body.embed .steps, body.embed .muted-link, body.embed .notice, body.embed footer,
  body.embed #dlPng, body.embed #dlAbc, body.embed #dlJson { display: none; }
  body.embed main { padding-top: 8px; }
  #soundGate { margin-top: 10px; padding: 10px 12px; border-radius: 8px; background: var(--chip); font-size: 14px; }
  #soundGate p { margin: 0 0 8px; color: var(--muted); }
</style>
""",
)

rep(
    """    if (ABCJS.synth.supportsAudio()) {
      if (!synthControl)""",
    """    if (ABCJS.synth.supportsAudio() && (!window.__gateSound || window.__soundAllowed)) {
      if (!synthControl)""",
)
rep(
    """    } else $("player").textContent = "Audio playback isn't supported in this browser.";""",
    """    } else if (ABCJS.synth.supportsAudio()) showSoundGate();
    else $("player").textContent = "Audio playback isn't supported in this browser.";""",
)
rep(
    "function renderNotation() {",
    """// Flotsam: abcjs plays by downloading instrument samples from paulrosen.github.io. That is a request to a third
// party, so in the app it only happens after the user taps Allow (and is asked again each time the score is opened).
function showSoundGate() {
  const el = $("player"); el.textContent = "";
  const box = document.createElement("div"); box.id = "soundGate";
  const p = document.createElement("p");
  p.textContent = "To play the score, small instrument sound files are downloaded from the abcjs sound library (paulrosen.github.io). Nothing about you or the score is sent.";
  const b = document.createElement("button"); b.className = "primary"; b.textContent = "Allow sounds and play";
  b.onclick = () => { window.__soundAllowed = true; renderNotation(); };
  box.append(p, b); el.appendChild(box);
}

function renderNotation() {""",
)

# the original hands a score over through sessionStorage from another page; inside the app that storage is shared
i = s.index("// Hand-off from groovebox.html")
j = s.index("</script>\n</body>")
s = s[:i] + s[j:]

rep(
    "</script>\n</body>",
    """</script>
<script>
// ---------- Flotsam bridge: the contract is src/results/frame/bridge.ts ----------
(function () {
  "use strict";
  if (window.parent === window) return;               // opened on its own: behave like the original page
  window.__gateSound = true;
  document.body.classList.add("embed");
  document.documentElement.setAttribute("data-theme", "dark");
  const ORIGIN = window.location.origin;
  const post = (m, transfer) => window.parent.postMessage(m, ORIGIN, transfer || []);
  let current = "score.yue2.json";
  window.addEventListener("message", (ev) => {
    if (ev.source !== window.parent || ev.origin !== ORIGIN) return;
    const d = ev.data;
    if (!d || d.type !== "load" || !(d.bytes instanceof ArrayBuffer)) return;
    try {
      const p = JSON.parse(new TextDecoder().decode(new Uint8Array(d.bytes)));
      if (!p || typeof p.abc !== "string" || !p.abc.trim()) throw new Error("This file is not a song score.");
      current = String(d.filename || current);
      window.YuE2Studio.loadPackage(p, current);
      post({ type: "loaded" });
    } catch (e) { post({ type: "error", message: String((e && e.message) || e) }); }
  });
  const keep = document.createElement("button");
  keep.className = "primary"; keep.textContent = "Save edited score";
  keep.onclick = () => {
    const issues = validate(model);
    if (issues.length && !confirm("The score has " + issues.length + " issue(s) YuE2 may reject or misread:\\n\\n" + issues.slice(0, 5).join("\\n") + "\\n\\nSave anyway?")) return;
    const bytes = new TextEncoder().encode(JSON.stringify(currentPackage(), null, 1));
    encodeM3DS(bytes, "song.yue2.json").arrayBuffer().then((buf) => post({ type: "save", filename: "yue2-score-edited.png", bytes: buf }, [buf]));
  };
  const row = document.getElementById("revert").parentNode; row.insertBefore(keep, row.firstChild);
  post({ type: "hello" });
})();
</script>
</body>""",
)

open(out, "w", encoding="utf8").write(s)
print("wrote", os.path.abspath(out), len(s), "bytes")
